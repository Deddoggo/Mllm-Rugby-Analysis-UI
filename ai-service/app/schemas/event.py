"""HTTP contracts for AI-owned rugby event detection."""

from pydantic import BaseModel, Field, model_validator


class EventDetectionRequest(BaseModel):
    """Processed video identity shared by the backend gateway."""

    video_path: str = Field(min_length=1)
    video_id: str = Field(min_length=1, pattern=r"^[A-Za-z0-9_-]+$")


class DetectedEventProposal(BaseModel):
    """Provider-neutral temporal proposal returned across the service boundary."""

    id: str = Field(min_length=1)
    label: str = Field(min_length=1)
    start: float = Field(ge=0)
    end: float = Field(gt=0)
    confidence: float = Field(ge=0, le=1)

    @model_validator(mode="after")
    def validate_boundaries(self) -> "DetectedEventProposal":
        if self.end <= self.start:
            raise ValueError("Event end must be after start.")
        return self


class EventDetectionResponse(BaseModel):
    """List of proposals generated by the configured detector."""

    events: list[DetectedEventProposal] = Field(default_factory=list)
